"""Generate CODE-INDEX.md: one line per tracked script with its first comment line (run from anywhere).

Usage: python3 scripts/gen-code-index.py          (writes CODE-INDEX.md)
       python3 scripts/gen-code-index.py --check  (exit 1 if CODE-INDEX.md is out of date; writes nothing)
Reads `git ls-files`. Skips archives/ and tests. The description is the script's first comment line
(PowerShell `#` or `<# #>`, Python docstring or `#`, shell `#`, cmd `REM`/`::`).
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "CODE-INDEX.md"
EXTS = {".ps1", ".psm1", ".py", ".sh", ".cmd", ".bat"}
SKIP_PARTS = {"archives", "tests", "__pycache__"}
MAX = 160


def tracked() -> list[str]:
    out = subprocess.run(
        ["git", "-C", str(ROOT), "ls-files", "-z"], capture_output=True, check=True
    ).stdout.decode("utf-8")
    files = []
    for rel in out.split("\0"):
        if not rel:
            continue
        p = Path(rel)
        if p.suffix.lower() not in EXTS:
            continue
        if SKIP_PARTS.intersection(p.parts[:-1]) or p.name.startswith("test_") or p.name.startswith("test-"):
            continue
        files.append(rel)
    return sorted(files, key=lambda r: (r.count("/") > 0, r.lower()))


def clean(text: str) -> str:
    text = " ".join(text.replace("|", "/").split())
    if len(text) > MAX:
        text = text[: MAX - 3].rstrip() + "..."
    return text


def describe(path: Path) -> str:
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return ""
    ext = path.suffix.lower()
    in_block = False
    doc = None
    for raw in lines[:60]:
        line = raw.strip().lstrip("\ufeff")
        if not line:
            continue
        if ext == ".py":
            if doc is None and (line.startswith('"""') or line.startswith("'''")):
                q = line[:3]
                body = line[3:]
                if body.endswith(q) and len(body) >= 3:
                    body = body[:-3]
                if body.strip():
                    return clean(body)
                doc = q
                continue
            if doc:
                return clean(line.rstrip(doc))
        if ext in (".ps1", ".psm1"):
            if line.startswith("<#"):
                rest = line[2:].replace("#>", "").strip()
                if rest and not rest.startswith("."):
                    return clean(rest)
                in_block = True
                continue
            if in_block:
                if line.startswith("#>"):
                    in_block = False
                    continue
                if line.startswith("."):
                    continue
                return clean(line)
        if ext in (".cmd", ".bat"):
            low = line.lower()
            if low.startswith("@echo") or low.startswith("setlocal"):
                continue
            for pre in ("rem ", "::"):
                if low.startswith(pre):
                    t = line[len(pre):].strip()
                    if t:
                        return clean(t)
                    break
            else:
                return ""
            continue
        if line.startswith("#!") or line.lower().startswith("#requires") or line.startswith("# -*-"):
            continue
        if line.startswith("#"):
            t = line.lstrip("#").strip()
            if t:
                return clean(t)
            continue
        if ext == ".py" and (line.startswith("from __future__") or line.startswith("import ")):
            continue
        return ""
    return ""


def render() -> str:
    out = [
        "# Code index (generated by scripts/gen-code-index.py; do not edit)",
        "",
        "One line per tracked script: path and its first comment line. Tests and archives/ are left out.",
        "Regenerate with `python3 scripts/gen-code-index.py`; CI runs it with `--check`.",
    ]
    group = None
    for rel in tracked():
        top = rel.split("/")[0] if "/" in rel else "(repo root)"
        if top != group:
            group = top
            out += ["", f"## {group}", "", "| File | What it does |", "|---|---|"]
        desc = describe(ROOT / rel) or "(no description comment)"
        out.append(f"| `{rel}` | {desc} |")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print("CODE-INDEX.md is out of date. Run: python3 scripts/gen-code-index.py, then commit it.")
            return 1
        print("CODE-INDEX.md is up to date.")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote CODE-INDEX.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
