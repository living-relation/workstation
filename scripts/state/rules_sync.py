#!/usr/bin/env python3
"""Generate Cursor rules from Claude rules. Stdlib only.

Each .claude/rules/<name>.md becomes .cursor/rules/<name>.mdc:
  front matter: description (copied), globs (from the Claude `paths`), alwaysApply (true when no paths)
  then a "generated, do not edit" line, then the rule body unchanged.
Generated .mdc files whose source is gone are removed. Hand-made .mdc files (no generated line)
are never touched.
Usage: rules_sync.py [--repo DIR] [--check]
Exit: 0 = written / in sync, 2 = --check found drift, 1 = no .claude/rules folder.
"""
import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import state_paths  # noqa: E402

SOURCE_DIR = Path(".claude") / "rules"
TARGET_DIR = Path(".cursor") / "rules"
GENERATED_MARK = "<!-- generated by rules_sync.py from %s; do not edit, edit the source and rerun -->"
GENERATED_PREFIX = "<!-- generated by rules_sync.py from "


def _unquote(value):
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def split_front_matter(text):
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, text
    for index in range(1, len(lines)):
        if lines[index].strip() == "---":
            return parse_front_matter(lines[1:index]), "\n".join(lines[index + 1:])
    return {}, text


def parse_front_matter(lines):
    data, key = {}, None
    for raw in lines:
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if stripped.startswith("- ") and key is not None:
            if not isinstance(data.get(key), list):
                data[key] = []
            data[key].append(_unquote(stripped[2:]))
            continue
        name, _, value = stripped.partition(":")
        key = name.strip()
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            data[key] = [_unquote(v) for v in value[1:-1].split(",") if v.strip()]
        elif value:
            data[key] = _unquote(value)
        else:
            data[key] = []
    return data


def _as_list(value):
    if isinstance(value, list):
        return value
    return [v.strip() for v in str(value).split(",") if v.strip()] if value else []


def render(source_rel, text):
    meta, body = split_front_matter(text)
    globs = _as_list(meta.get("paths") or meta.get("globs"))
    description = meta.get("description") if isinstance(meta.get("description"), str) else ""
    out = ["---", "description: %s" % description, "globs: %s" % ",".join(globs),
           "alwaysApply: %s" % ("false" if globs else "true"), "---",
           GENERATED_MARK % source_rel]
    body = body.strip("\n")
    if body:
        out += ["", body]
    return "\n".join(out) + "\n"


def is_generated(path):
    try:
        return GENERATED_PREFIX in path.read_text(encoding="utf-8-sig", errors="replace")
    except OSError:
        return False


def plan(root):
    sources = sorted((root / SOURCE_DIR).glob("*.md"))
    wanted = {}
    for source in sources:
        rel = (SOURCE_DIR / source.name).as_posix()
        text = source.read_text(encoding="utf-8-sig")
        wanted[root / TARGET_DIR / (source.stem + ".mdc")] = render(rel, text)
    stale = [p for p in sorted((root / TARGET_DIR).glob("*.mdc")) if p not in wanted and is_generated(p)]
    return wanted, stale


def _current(path):
    try:
        with open(path, encoding="utf-8", newline="") as handle:
            return handle.read().replace("\r\n", "\n")
    except OSError:
        return None


def main(argv=None):
    state_paths.configure_output()
    parser = argparse.ArgumentParser(description="Generate .cursor/rules/*.mdc from .claude/rules/*.md.")
    parser.add_argument("--repo", default=".")
    parser.add_argument("--check", action="store_true", help="report drift, write nothing")
    args = parser.parse_args(argv)
    top = state_paths._git(args.repo, "rev-parse", "--show-toplevel")
    root = Path(top) if top else Path(args.repo).resolve()
    if not (root / SOURCE_DIR).is_dir():
        print("rules_sync: no %s in %s" % (SOURCE_DIR.as_posix(), root), file=sys.stderr)
        return 1
    wanted, stale = plan(root)
    drift = []
    for path, text in wanted.items():
        current = _current(path)
        if current != text:
            drift.append("%s %s" % ("MISSING" if current is None else "DRIFT", path.relative_to(root).as_posix()))
            if not args.check:
                if current is not None and not is_generated(path):
                    print("rules_sync: replacing hand-made %s" % path.relative_to(root).as_posix())
                path.parent.mkdir(parents=True, exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as handle:
                    handle.write(text)
    for path in stale:
        drift.append("ORPHAN %s" % path.relative_to(root).as_posix())
        if not args.check:
            path.unlink()
    if args.check:
        for line in drift:
            print(line)
        if drift:
            print("rules_sync: %d Cursor rule(s) out of sync; run rules_sync.py" % len(drift))
            return 2
        print("rules_sync: in sync (%d rule(s))" % len(wanted))
        return 0
    print("rules_sync: %d rule(s), %d change(s)" % (len(wanted), len(drift)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
